package docs

import (
	"fmt"
	"path/filepath"

	"helmvalues/pkg/docs/templates"
)

// Disclaimer returns the "generated document" comment written at the top of
// the rendered README, in the plan's markup, followed by a blank line. It
// names the chart's README template when the chart has one, since that is
// the file to edit instead.
func (p *Plan) Disclaimer() (string, error) {
	markup, err := p.DocsMarkup()
	if err != nil {
		return "", err
	}

	return disclaimerComment(markup, p.disclaimerSource()), nil
}

// disclaimerSource names the files the README is generated from. Only the
// chart's own template is named: a --template path may be outside the chart
// or machine-specific, which would make the output differ between machines.
func (p *Plan) disclaimerSource() string {
	if p.cfg.Template != "" {
		return "values.yaml and a README template"
	}

	if tmpl := p.DocsChartReadmeTemplate(); tmpl != "" {
		return "values.yaml and " + filepath.Base(tmpl)
	}

	return "values.yaml"
}

// disclaimerComment renders the disclaimer text as a comment in markup.
func disclaimerComment(markup templates.Markup, source string) string {
	text := fmt.Sprintf("Generated by helm-values from %s. DO NOT EDIT. Run `helm values docs` to regenerate.", source)

	if markup == templates.ReStructuredText {
		return ".. " + text + "\n\n"
	}

	return "<!-- " + text + " -->\n\n"
}
