package docs_test

import (
	"io"
	"maps"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"helmvalues/pkg/docs"
	"helmvalues/pkg/docs/templates"

	"github.com/samber/mo"
	"github.com/sirupsen/logrus"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const (
	testChartFile  = "apiVersion: v2\nname: mychart\nversion: 0.1.0\ndescription: A test chart\n"
	testValuesFile = "# -- replicas to run\nreplicas: 1\n"
	mdDisclaimer   = "<!-- Generated by helm-values from values.yaml. DO NOT EDIT. Run `helm values docs` to regenerate. -->\n\n"
	rstDisclaimer  = ".. Generated by helm-values from values.yaml. DO NOT EDIT. Run `helm values docs` to regenerate.\n\n"
)

// writeChart writes a chart to a temp dir, plus any extra files (name -> content).
func writeChart(t *testing.T, extra map[string]string) string {
	t.Helper()

	dir := t.TempDir()

	files := map[string]string{"Chart.yaml": testChartFile, "values.yaml": testValuesFile}
	maps.Copy(files, extra)

	for name, content := range files {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600))
	}

	return dir
}

func docsConfig(markup mo.Option[templates.Markup]) *docs.Config {
	return &docs.Config{
		LogLevel:       logrus.InfoLevel,
		StdOut:         false,
		Strict:         false,
		DryRun:         false,
		GitAdd:         false,
		Check:          false,
		UseDefault:     mo.None[bool](),
		Output:         mo.None[string](),
		Template:       "",
		ExtraTemplates: nil,
		Markup:         markup,
		Order:          docs.ValuesOrderPreserve,
	}
}

func generateReadme(t *testing.T, dir string, cfg *docs.Config, readme string) string {
	t.Helper()

	logger := logrus.New()
	logger.SetOutput(io.Discard)

	require.NoError(t, docs.GenerateDocs(logger, cfg, []string{dir}))

	content, err := os.ReadFile(filepath.Join(dir, readme)) //nolint:gosec // test-controlled temp dir path
	require.NoError(t, err)

	return string(content)
}

func TestReadmeStartsWithMarkdownDisclaimer(t *testing.T) {
	t.Parallel()

	dir := writeChart(t, nil)

	content := generateReadme(t, dir, docsConfig(mo.None[templates.Markup]()), "README.md")

	require.True(t, strings.HasPrefix(content, mdDisclaimer), "got:\n%s", content)
	// exactly one blank line between the disclaimer and the template output
	assert.True(t, strings.HasPrefix(content, mdDisclaimer+"# mychart"), "got:\n%s", content)
}

func TestReadmeStartsWithRstDisclaimer(t *testing.T) {
	t.Parallel()

	dir := writeChart(t, nil)

	content := generateReadme(t, dir, docsConfig(mo.Some(templates.ReStructuredText)), "README.rst")

	// RST requires the blank line, or the next line becomes part of the comment
	assert.True(t, strings.HasPrefix(content, rstDisclaimer+"======="), "got:\n%s", content)
}

func TestReadmeDisclaimerNamesChartTemplate(t *testing.T) {
	t.Parallel()

	dir := writeChart(t, map[string]string{
		"README.md.gotmpl": "{{ template \"md.header\" . }}\nCustom intro.\n",
	})

	content := generateReadme(t, dir, docsConfig(mo.None[templates.Markup]()), "README.md")

	want := "<!-- Generated by helm-values from values.yaml and README.md.gotmpl. " +
		"DO NOT EDIT. Run `helm values docs` to regenerate. -->\n\n# mychart\nCustom intro.\n"
	assert.Equal(t, want, content)
}

func TestReadmeCheckIncludesDisclaimer(t *testing.T) {
	t.Parallel()

	dir := writeChart(t, nil)
	content := generateReadme(t, dir, docsConfig(mo.None[templates.Markup]()), "README.md")

	logger := logrus.New()
	logger.SetOutput(io.Discard)

	checkCfg := docsConfig(mo.None[templates.Markup]())
	checkCfg.Check = true

	// freshly generated README passes the check
	require.NoError(t, docs.GenerateDocs(logger, checkCfg, []string{dir}))

	// a README without the disclaimer is stale
	stale := strings.TrimPrefix(content, mdDisclaimer)
	require.NoError(t, os.WriteFile(filepath.Join(dir, "README.md"), []byte(stale), 0o600))
	require.Error(t, docs.GenerateDocs(logger, checkCfg, []string{dir}))
}
